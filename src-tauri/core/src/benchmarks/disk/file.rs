//! The temporary benchmark file and everything that keeps it safe.
//!
//! The file lives in a dedicated hidden directory, has a strictly validated
//! name, is created exclusively (an existing file is never opened or
//! overwritten), is private to the user, and is removed when the guard is
//! dropped: after success, failure, cancellation or a panic. Leftovers from a
//! crash are removed at the next start, but only files matching the exact
//! pattern inside the dedicated directory.

#![cfg(unix)]

use std::fs::{DirBuilder, File, OpenOptions};
use std::os::fd::AsRawFd;
use std::os::unix::fs::{DirBuilderExt, FileExt, OpenOptionsExt};
use std::path::{Path, PathBuf};
use std::time::{Duration, SystemTime};

use super::super::BenchmarkError;
use super::super::model::IoMode;
use super::aligned::{ALIGN, AlignedBuf};

pub const DIR_NAME: &str = ".taskmanager-benchmark";
const FILE_PREFIX: &str = ".tm-bench-";
const FILE_SUFFIX: &str = ".tmp";

/// Run ids are generated by the coordinator; only these characters are ever
/// allowed into a file name.
pub fn valid_run_id(id: &str) -> bool {
    !id.is_empty()
        && id.len() <= 64
        && id
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
}

/// Exactly the names this module creates, and nothing else.
pub fn is_benchmark_file_name(name: &str) -> bool {
    name.strip_prefix(FILE_PREFIX)
        .and_then(|rest| rest.strip_suffix(FILE_SUFFIX))
        .is_some_and(valid_run_id)
}

pub(super) fn io_error(what: &str, e: &std::io::Error) -> BenchmarkError {
    BenchmarkError::Failed(match e.kind() {
        std::io::ErrorKind::PermissionDenied => format!(
            "Permission denied: this account cannot {what} in that location. Choose another location."
        ),
        _ if e.raw_os_error() == Some(libc::ENOSPC) => {
            "The drive ran out of space during the test.".into()
        }
        _ => format!("Could not {what}: {e}"),
    })
}

pub struct BenchFile {
    file: File,
    path: PathBuf,
    dir: PathBuf,
    mode: IoMode,
    mode_note: Option<String>,
}

const NO_DIRECT: &str = "This filesystem does not support direct I/O, so buffered I/O was used. Results reflect the page cache as well as the drive.";

impl BenchFile {
    /// Creates the file in `<parent>/.taskmanager-benchmark/`. With
    /// `want_direct`, tries `O_DIRECT` and falls back to buffered I/O (with a
    /// note) when the filesystem will not do direct I/O.
    pub fn create(parent: &Path, run_id: &str, want_direct: bool) -> Result<Self, BenchmarkError> {
        if !valid_run_id(run_id) {
            return Err(BenchmarkError::Failed("Invalid run id.".into()));
        }
        let dir = parent.join(DIR_NAME);
        ensure_private_dir(&dir)?;
        let path = dir.join(format!("{FILE_PREFIX}{run_id}{FILE_SUFFIX}"));

        let mut note = None;
        if want_direct && cfg!(target_os = "linux") {
            match open_new(&path, true) {
                Ok(file) if direct_io_works(&file) => {
                    return Ok(Self {
                        file,
                        path,
                        dir,
                        mode: IoMode::Direct,
                        mode_note: None,
                    });
                }
                Ok(_) => {
                    // Opened, but real direct I/O fails here. Start clean.
                    let _ = std::fs::remove_file(&path);
                    note = Some(NO_DIRECT.to_owned());
                }
                Err(e) if is_direct_unsupported(&e) => note = Some(NO_DIRECT.to_owned()),
                Err(e) => return Err(io_error("create the test file", &e)),
            }
        } else if want_direct {
            note = Some("Direct I/O is not available on this platform.".into());
        }
        let file = open_new(&path, false).map_err(|e| io_error("create the test file", &e))?;
        Ok(Self {
            file,
            path,
            dir,
            mode: IoMode::Buffered,
            mode_note: note,
        })
    }

    pub fn file(&self) -> &File {
        &self.file
    }

    pub fn mode(&self) -> IoMode {
        self.mode
    }

    pub fn mode_note(&self) -> Option<&str> {
        self.mode_note.as_deref()
    }

    pub fn path(&self) -> &Path {
        &self.path
    }

    /// Flushes written data to the device (`fdatasync`).
    pub fn sync(&self) -> Result<(), BenchmarkError> {
        self.file
            .sync_data()
            .map_err(|e| io_error("flush the test file", &e))
    }

    /// Drops this file's cached pages (not the whole system's), so buffered
    /// reads come from the device. Direct I/O never uses the cache.
    pub fn drop_own_cache(&self) {
        // SAFETY: the descriptor is valid for the lifetime of `self.file`;
        // posix_fadvise only advises the kernel.
        unsafe {
            libc::posix_fadvise(self.file.as_raw_fd(), 0, 0, libc::POSIX_FADV_DONTNEED);
        }
    }
}

impl Drop for BenchFile {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(&self.path);
        // Only succeeds when the directory is empty.
        let _ = std::fs::remove_dir(&self.dir);
    }
}

#[cfg(target_os = "linux")]
const O_DIRECT: i32 = libc::O_DIRECT;
#[cfg(not(target_os = "linux"))]
const O_DIRECT: i32 = 0;

fn open_new(path: &Path, direct: bool) -> std::io::Result<File> {
    let mut o = OpenOptions::new();
    o.read(true).write(true).create_new(true).mode(0o600);
    if direct {
        o.custom_flags(O_DIRECT);
    }
    o.open(path)
}

fn is_direct_unsupported(e: &std::io::Error) -> bool {
    matches!(e.raw_os_error(), Some(libc::EINVAL | libc::EOPNOTSUPP))
}

/// An aligned write must really succeed: some filesystems accept the flag at
/// open and fail (or silently ignore it) later.
fn direct_io_works(file: &File) -> bool {
    AlignedBuf::new(ALIGN).is_some_and(|b| file.write_at(b.as_slice(), 0).is_ok())
}

/// In a shared location such as `/tmp` another user could create the folder
/// first, so an existing one is used only if it is ours and private.
fn ensure_private_dir(dir: &Path) -> Result<(), BenchmarkError> {
    use std::os::unix::fs::MetadataExt;
    let meta = match std::fs::symlink_metadata(dir) {
        Ok(meta) => meta,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            DirBuilder::new()
                .mode(0o700)
                .create(dir)
                .map_err(|e| io_error("create the benchmark folder", &e))?;
            std::fs::symlink_metadata(dir)
                .map_err(|e| io_error("inspect the benchmark folder", &e))?
        }
        Err(e) => return Err(io_error("inspect the benchmark folder", &e)),
    };
    if meta.file_type().is_symlink() || !meta.is_dir() {
        return Err(BenchmarkError::Failed(
            "The benchmark folder is not a plain folder; refusing to use it.".into(),
        ));
    }
    // SAFETY: getuid has no preconditions and cannot fail.
    if meta.uid() != unsafe { libc::getuid() } {
        return Err(BenchmarkError::Failed(format!(
            "The benchmark folder {} belongs to another user; refusing to use it.",
            dir.display()
        )));
    }
    if meta.mode() & 0o777 != 0o700 {
        return Err(BenchmarkError::Failed(format!(
            "The benchmark folder {} can be opened by other users; refusing to use it. Remove it or make it private (chmod 700).",
            dir.display()
        )));
    }
    Ok(())
}

/// Free space available to this user at `path`, in bytes.
pub fn free_bytes(path: &Path) -> Option<u64> {
    use std::os::unix::ffi::OsStrExt;
    let c = std::ffi::CString::new(path.as_os_str().as_bytes()).ok()?;
    // SAFETY: `c` is a valid NUL-terminated path and `st` is a plain struct
    // that statvfs fully initialises on success.
    unsafe {
        let mut st: libc::statvfs = std::mem::zeroed();
        (libc::statvfs(c.as_ptr(), &mut st) == 0)
            .then(|| (st.f_bavail as u64).saturating_mul(st.f_frsize as u64))
    }
}

/// Whether this user can create files in `dir`.
pub fn is_writable(dir: &Path) -> bool {
    use std::os::unix::ffi::OsStrExt;
    std::ffi::CString::new(dir.as_os_str().as_bytes())
        // SAFETY: valid NUL-terminated path; access() only reads it.
        .is_ok_and(|c| unsafe { libc::access(c.as_ptr(), libc::W_OK | libc::X_OK) } == 0)
}

/// Removes benchmark files left behind by a crash. Only regular files whose
/// names match the exact pattern, inside the dedicated directory, and older
/// than `min_age` are touched. Returns how many were removed.
pub fn cleanup_stale(parent: &Path, min_age: Duration) -> usize {
    let dir = parent.join(DIR_NAME);
    match std::fs::symlink_metadata(&dir) {
        Ok(m) if m.is_dir() && !m.file_type().is_symlink() => {}
        _ => return 0,
    }
    let Ok(entries) = std::fs::read_dir(&dir) else {
        return 0;
    };
    let mut removed = 0;
    for entry in entries.flatten() {
        let Some(name) = entry.file_name().to_str().map(str::to_owned) else {
            continue;
        };
        if !is_benchmark_file_name(&name) {
            continue;
        }
        let Ok(meta) = std::fs::symlink_metadata(entry.path()) else {
            continue;
        };
        let old = meta
            .modified()
            .ok()
            .and_then(|m| SystemTime::now().duration_since(m).ok())
            .is_some_and(|age| age >= min_age);
        if meta.is_file() && old && std::fs::remove_file(entry.path()).is_ok() {
            removed += 1;
        }
    }
    let _ = std::fs::remove_dir(&dir);
    removed
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::os::unix::fs::symlink;

    fn tmp() -> tempfile::TempDir {
        tempfile::tempdir().expect("temp dir")
    }

    #[test]
    fn only_our_exact_names_are_recognised() {
        assert!(is_benchmark_file_name(".tm-bench-disk-123-0.tmp"));
        for bad in [
            "tm-bench-disk-1.tmp",
            ".tm-bench-.tmp",
            ".tm-bench-DISK-1.tmp",
            ".tm-bench-a/b.tmp",
            ".tm-bench-a..b.tmp",
            ".tm-bench-a b.tmp",
            ".tm-bench-disk-1.tmp.bak",
            "photo.jpg",
            "",
        ] {
            assert!(!is_benchmark_file_name(bad), "{bad:?}");
        }
        assert!(!is_benchmark_file_name(&format!(
            ".tm-bench-{}.tmp",
            "a".repeat(65)
        )));
    }

    #[test]
    fn creating_and_dropping_leaves_nothing_behind() {
        let d = tmp();
        {
            // Buffered: this test is about cleanup, and a direct-I/O file
            // rejects the unaligned write below on real disk filesystems
            // (tmpfs silently falls back, which hid that locally).
            let f = BenchFile::create(d.path(), "disk-1-0", false).expect("creates");
            assert!(f.path().exists());
            assert!(f.path().starts_with(d.path().join(DIR_NAME)));
            f.file().write_all_at(b"hello", 0).unwrap();
        }
        // File and the (now empty) directory are gone.
        assert!(!d.path().join(DIR_NAME).exists());
    }

    #[test]
    fn cleanup_happens_on_a_panic_too() {
        let d = tmp();
        let p = d.path().to_path_buf();
        let r = std::panic::catch_unwind(move || {
            let _f = BenchFile::create(&p, "disk-2-0", false).unwrap();
            panic!("benchmark blew up");
        });
        assert!(r.is_err());
        assert!(!d.path().join(DIR_NAME).exists());
    }

    #[test]
    fn an_existing_file_is_never_opened_or_overwritten() {
        let d = tmp();
        let dir = d.path().join(DIR_NAME);
        DirBuilder::new().mode(0o700).create(&dir).unwrap();
        let existing = dir.join(".tm-bench-disk-3-0.tmp");
        std::fs::write(&existing, b"precious").unwrap();
        assert!(BenchFile::create(d.path(), "disk-3-0", false).is_err());
        assert_eq!(std::fs::read(&existing).unwrap(), b"precious");
    }

    #[test]
    fn an_existing_folder_others_can_open_is_refused() {
        use std::os::unix::fs::PermissionsExt;
        let d = tmp();
        let dir = d.path().join(DIR_NAME);
        std::fs::create_dir(&dir).unwrap();
        std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o755)).unwrap();
        let e = BenchFile::create(d.path(), "disk-3-1", false)
            .err()
            .expect("refused");
        assert!(e.to_string().contains("other users"), "{e}");
        assert_eq!(std::fs::read_dir(&dir).unwrap().count(), 0);

        std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o700)).unwrap();
        assert!(BenchFile::create(d.path(), "disk-3-1", false).is_ok());
    }

    #[test]
    fn bad_run_ids_cannot_escape_the_directory() {
        let d = tmp();
        for id in ["", "../evil", "a/b", "UP", "a b", "x\0y"] {
            assert!(BenchFile::create(d.path(), id, false).is_err(), "{id:?}");
        }
        assert!(!d.path().join("evil").exists());
    }

    #[test]
    fn a_symlinked_benchmark_folder_is_refused() {
        let d = tmp();
        let target = d.path().join("elsewhere");
        std::fs::create_dir(&target).unwrap();
        symlink(&target, d.path().join(DIR_NAME)).unwrap();
        let e = BenchFile::create(d.path(), "disk-4-0", false)
            .err()
            .expect("refused");
        assert!(e.to_string().contains("not a plain folder"), "{e}");
        assert_eq!(
            std::fs::read_dir(&target).unwrap().count(),
            0,
            "nothing written through it"
        );
    }

    #[test]
    fn the_file_is_private_to_the_user() {
        use std::os::unix::fs::PermissionsExt;
        let d = tmp();
        let f = BenchFile::create(d.path(), "disk-5-0", false).unwrap();
        let mode = std::fs::metadata(f.path()).unwrap().permissions().mode() & 0o777;
        assert_eq!(mode, 0o600);
        let dmode = std::fs::metadata(d.path().join(DIR_NAME))
            .unwrap()
            .permissions()
            .mode()
            & 0o777;
        assert_eq!(dmode, 0o700);
    }

    #[test]
    fn buffered_mode_is_reported_with_a_reason_when_direct_is_unavailable() {
        let d = tmp();
        let f = BenchFile::create(d.path(), "disk-6-0", true).unwrap();
        match f.mode() {
            // The temp filesystem supports direct I/O: no note needed.
            IoMode::Direct => assert!(f.mode_note().is_none()),
            IoMode::Buffered => assert!(f.mode_note().is_some_and(|n| n.contains("page cache"))),
        }
        let b = BenchFile::create(d.path(), "disk-7-0", false).unwrap();
        assert_eq!(b.mode(), IoMode::Buffered);
        assert!(
            b.mode_note().is_none(),
            "buffered by request needs no apology"
        );
    }

    #[test]
    fn stale_cleanup_removes_only_matching_old_regular_files() {
        let d = tmp();
        let dir = d.path().join(DIR_NAME);
        std::fs::create_dir(&dir).unwrap();
        std::fs::write(dir.join(".tm-bench-disk-9-0.tmp"), b"x").unwrap();
        std::fs::write(dir.join(".tm-bench-disk-9-1.tmp"), b"x").unwrap();
        std::fs::write(dir.join("notes.txt"), b"keep me").unwrap();
        std::fs::write(dir.join(".tm-bench-DISK.tmp"), b"keep me too").unwrap();
        // A symlink with a matching name must not be followed or removed.
        let victim = d.path().join("victim");
        std::fs::write(&victim, b"do not delete").unwrap();
        symlink(&victim, dir.join(".tm-bench-disk-link-0.tmp")).unwrap();

        // Too young: nothing happens.
        assert_eq!(cleanup_stale(d.path(), Duration::from_secs(3600)), 0);
        assert!(dir.join(".tm-bench-disk-9-0.tmp").exists());

        assert_eq!(cleanup_stale(d.path(), Duration::ZERO), 2);
        assert!(!dir.join(".tm-bench-disk-9-0.tmp").exists());
        assert!(dir.join("notes.txt").exists());
        assert!(dir.join(".tm-bench-DISK.tmp").exists());
        assert_eq!(std::fs::read(&victim).unwrap(), b"do not delete");
    }

    #[test]
    fn stale_cleanup_ignores_a_missing_or_symlinked_directory() {
        let d = tmp();
        assert_eq!(cleanup_stale(d.path(), Duration::ZERO), 0);
        let real = d.path().join("real");
        std::fs::create_dir(&real).unwrap();
        std::fs::write(real.join(".tm-bench-disk-1-0.tmp"), b"x").unwrap();
        symlink(&real, d.path().join(DIR_NAME)).unwrap();
        assert_eq!(cleanup_stale(d.path(), Duration::ZERO), 0);
        assert!(real.join(".tm-bench-disk-1-0.tmp").exists());
    }

    #[test]
    fn free_space_and_writability_are_reported() {
        let d = tmp();
        assert!(free_bytes(d.path()).is_some_and(|b| b > 0));
        assert_eq!(free_bytes(Path::new("/definitely/not/here")), None);
        assert!(is_writable(d.path()));
        assert!(!is_writable(Path::new("/proc")));
    }
}
