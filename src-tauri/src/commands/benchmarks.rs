//! Benchmark commands. The frontend can only pick a kind, a profile (both
//! enums) and a graphics adapter id; nothing else about a run is controlled
//! from the UI.

use std::sync::Arc;

use tauri::{AppHandle, Emitter, State};

use crate::state::AppState;
use tm_core::benchmarks::coordinator::ProgressSink;
use tm_core::benchmarks::{
    BenchmarkKind, BenchmarkProfile, BenchmarkResult, BenchmarkStatus, GpuAdapterInfo,
};
use tm_core::errors::{AppError, AppResult};

pub const STATUS_EVENT: &str = "benchmark://status";
pub const RESULT_EVENT: &str = "benchmark://result";

/// Forwards progress to the webview as events. The coordinator already limits
/// updates to about ten per second.
struct EventSink(AppHandle);

impl ProgressSink for EventSink {
    fn status(&self, status: &BenchmarkStatus) {
        let _ = self
            .0
            .emit_to(crate::desktop::MAIN_WINDOW, STATUS_EVENT, status);
    }

    fn finished(&self, result: &BenchmarkResult) {
        let _ = self
            .0
            .emit_to(crate::desktop::MAIN_WINDOW, RESULT_EVENT, result);
    }
}

/// Ids are generated by the backend (`vulkan-8086-a7ac-0`, `cpu-<millis>-<n>`);
/// anything else cannot name an adapter or a result, so it is rejected here.
fn valid_id(id: &str) -> bool {
    !id.is_empty() && id.len() <= 64 && id.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-')
}

#[tauri::command]
pub async fn start_benchmark(
    app: AppHandle,
    state: State<'_, AppState>,
    kind: BenchmarkKind,
    profile: BenchmarkProfile,
    adapter: Option<String>,
) -> AppResult<BenchmarkStatus> {
    if adapter.as_deref().is_some_and(|a| !valid_id(a)) {
        return Err(AppError::InvalidArgument("Not a valid adapter id.".into()));
    }
    let benchmarks = Arc::clone(&state.benchmarks);
    super::blocking::run(move || {
        super::confirm::confirm(&app, &format!(
            "Start the {profile:?} {kind:?} benchmark? It will place heavy load on your hardware. You can cancel it from Benchmarks."
        ))?;
        benchmarks.start(kind, profile, adapter, Arc::new(EventSink(app)))
    }).await
}

/// Graphics adapters for the GPU benchmark. Loading a graphics driver can
/// take a moment, so this runs off the UI thread.
#[tauri::command]
pub async fn list_gpu_adapters(state: State<'_, AppState>) -> AppResult<Vec<GpuAdapterInfo>> {
    let benchmarks = Arc::clone(&state.benchmarks);
    super::blocking::run(move || benchmarks.gpu_adapters()).await
}

#[tauri::command]
pub fn cancel_benchmark(state: State<'_, AppState>) {
    state.benchmarks.cancel();
}

#[tauri::command]
pub fn get_benchmark_status(state: State<'_, AppState>) -> BenchmarkStatus {
    state.benchmarks.status()
}

#[tauri::command]
pub fn get_benchmark_history(state: State<'_, AppState>) -> Vec<BenchmarkResult> {
    state.benchmarks.history()
}

#[tauri::command]
pub async fn delete_benchmark_result(
    app: AppHandle,
    state: State<'_, AppState>,
    id: String,
) -> AppResult<()> {
    if !valid_id(&id) {
        return Err(AppError::InvalidArgument("Not a valid result id.".into()));
    }
    let benchmarks = Arc::clone(&state.benchmarks);
    super::blocking::run(move || {
        super::confirm::confirm(
            &app,
            "Delete this saved benchmark result? This cannot be undone.",
        )?;
        benchmarks.delete_result(&id)
    })
    .await
}
